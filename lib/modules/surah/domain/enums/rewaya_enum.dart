  /// Number of ayahs in each surah. Index is surah number minus 1.
  final List<int> ayahCounts;

  const QuranRiwaya(this.ayahCounts);

  /// Returns the ayah count for [surahNumber] (1..114).
  int ayahCount(int surahNumber) {
    if (surahNumber < 1 || surahNumber > 114) {
      throw RangeError.range(surahNumber, 1, 114, 'surahNumber');
    }
    return ayahCounts[surahNumber - 1];
  }

  QuranRiwaya fromString(String s){
    switch (s) {
      case "bazzi":
        return QuranRiwaya.bazzi;
      case "duri":
        return QuranRiwaya.duri;
      case "hafs":
        return QuranRiwaya.hafs;
      case "qalun":
        return QuranRiwaya.qalun;
      case "shubah":
        return QuranRiwaya.shubah;
      case "susi":
        return QuranRiwaya.susi;
      case "warsh":
        return QuranRiwaya.warsh;
      default:
        throw Exception("Invalid riwaya: $s");
    }
  }

  /// Total number of ayahs in this riwaya.
  int get totalAyahs => ayahCounts.fold(0, (sum, count) => sum + count);
